# Variables of different data types

name = "Rahul"
age = 22
height = 172.5
cgpa = 8.75
is_student = True

print("Name:", name)
print("Age:", age)
print("Height:", height)
print("CGPA:", cgpa)
print("Student:", is_student)

print("\nData Types")
print(type(name))
print(type(age))
print(type(height))
print(type(cgpa))
print(type(is_student))

# Type Conversion
print("\nType Conversion")
age_float = float(age)
cgpa_int = int(cgpa)

print("Age after conversion:", age_float)
print("CGPA after conversion:", cgpa_int)